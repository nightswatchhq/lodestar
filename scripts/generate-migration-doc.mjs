// Writes docs/MIGRATION.md from src/lib/migration.ts, so the repo's account of the migration and
// the dashboard's are the same account. A test asserts the committed file is current.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const { buildInventory, summarise, ROUTES_AT_BASELINE } = await import('../src/lib/migration.ts');
const { ROUTE_FILES } = await import('../src/lib/route-files.generated.ts');

export function renderDoc() {
  const inv = buildInventory(ROUTE_FILES);
  const s = summarise(inv);
  const L = [];
  L.push('# Backend migration: Next to kittiwake');
  L.push('');
  L.push('<!-- Generated by scripts/generate-migration-doc.mjs. Do not edit by hand:');
  L.push('     run `pnpm migration:doc`. The source is src/lib/migration.ts, which is also what');
  L.push('     the edge routes from and what /migration renders. -->');
  L.push('');
  L.push(`**${s.remaining} route files left in this repo.** The goal is none: Lodestar is a frontend and kittiwake is the backend. ` +
    `That is **${s.percentToFrontend}%** of the way from ${ROUTES_AT_BASELINE} on 10 September 2026.`);
  L.push('');
  L.push(`Of the port itself, **${s.onKittiwake} of ${s.inScope}** are across, **${s.percent}%**. ` +
    `Of the rest, **${s.readyToCutOver} are written and answering on kittiwake already** and wait only on a cutover, ` +
    `and **${s.onNext}** have still to be ported.`);
  L.push('');
  L.push(`That second denominator is routes meant to move that have not yet, and it excludes ` +
    `${s.doomed} agreed for deletion, ${s.stayingOnNext} staying on Next by decision, and ` +
    `${s.scheduled} scheduled endpoints. The first counts all of them, because a route that stays ` +
    `by decision is still a route this repo serves. Each is listed below rather than quietly ` +
    `improving either figure.`);
  L.push('');
  L.push('## By block of work');
  L.push('');
  L.push('| Block | Done | Left |');
  L.push('|---|---|---|');
  for (const w of s.byWorkstream) L.push(`| ${w.workstream} | ${w.onKittiwake}/${w.total} | ${w.onNext} |`);
  L.push('');

  const section = (title, rows, withNote) => {
    if (rows.length === 0) return;
    L.push(`## ${title}`);
    L.push('');
    if (withNote) {
      L.push('| Route | Why |');
      L.push('|---|---|');
      for (const r of rows) L.push(`| \`${r.path}\` | ${r.note ?? ''} |`);
    } else {
      for (const r of rows) L.push(`- \`${r.path}\``);
    }
    L.push('');
  };

  section('On kittiwake', inv.filter((r) => r.state === 'kittiwake'), false);
  section('Still on Next', inv.filter((r) => r.state === 'next'), false);
  section('Staying on Next by decision', inv.filter((r) => r.state === 'staying'), true);
  section('Written on kittiwake, still routed here', inv.filter((r) => r.state === 'ready'), true);
  section('To be deleted rather than ported', inv.filter((r) => r.state === 'doomed'), true);

  return L.join('\n') + '\n';
}

// Importable by the freshness test without writing anything.
if (process.argv[1]?.endsWith('generate-migration-doc.mjs')) {
  writeFileSync(join(process.cwd(), 'docs', 'MIGRATION.md'), renderDoc());
  console.log('wrote docs/MIGRATION.md');
}
