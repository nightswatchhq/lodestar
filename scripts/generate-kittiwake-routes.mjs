// Regenerates src/lib/kittiwake-routes.generated.ts from kittiwake's own OpenAPI document.
//
//   node scripts/generate-kittiwake-routes.mjs
//   KITTIWAKE_OPENAPI=http://127.0.0.1:8080/openapi.json node scripts/...
//
// kittiwake generates that document from its router, so it cannot describe a route that does not
// exist or omit one that does. It publishes two lists: `paths`, which are described, and
// `x-withheld`, which are served and deliberately not described. Both are routes this frontend may
// call, and a check built on `paths` alone reports every withheld one as missing - seventeen of
// them, which is enough phantom failures to get the check switched off.
//
// Committed rather than fetched at test time: a unit test that needs the network is a unit test
// that fails when the network has a bad afternoon, and reports that as the frontend being wrong.

import { writeFileSync } from 'node:fs';

const SOURCE = process.env.KITTIWAKE_OPENAPI ?? 'https://api.lodestar-dashboard.com/openapi.json';

const res = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
if (!res.ok) {
  console.error(`${SOURCE} answered ${res.status}; nothing was written.`);
  process.exit(1);
}
const doc = await res.json();

const described = Object.keys(doc.paths ?? {});
const withheld = (doc['x-withheld'] ?? []).map((e) => e.path);

if (described.length === 0) {
  console.error('the document describes no paths at all; refusing to write an empty inventory.');
  process.exit(1);
}
if (withheld.length === 0) {
  console.error(
    'the document carries no x-withheld. An older kittiwake, or one that stopped publishing it:\n' +
      'either way this would write an inventory missing every withheld route. Nothing was written.',
  );
  process.exit(1);
}

const all = [...new Set([...described, ...withheld])].sort();

const file = `/**
 * Every route kittiwake serves, as it describes itself.
 *
 * Generated by \`scripts/generate-kittiwake-routes.mjs\` from \`/openapi.json\`. Do not edit by hand.
 *
 * Two lists go in: the routes the document describes, and the routes it withholds. A withheld one
 * is served and deliberately not documented - the Dock's session, the arbitrary-SQL tier, the
 * diagnostics - and this frontend calls seventeen of them, so an inventory built on the described
 * half alone would call every one of those a route that does not exist.
 *
 * \`kittiwake-routes.test.ts\` holds every \`/api/…\` path this app names against this list. That is
 * the check that catches a call site outliving the route behind it, which has happened: a monitor
 * was found probing a route deleted weeks earlier, and nothing noticed because it answered 404
 * quietly into a swallowed catch.
 */

/** Described in the OpenAPI document, in the shape it uses: \`{param}\` for a path segment. */
export const KITTIWAKE_DESCRIBED: readonly string[] = ${JSON.stringify(described.sort(), null, 2).replace(/"/g, "'")};

/** Served, deliberately undescribed. Still callable, still ours to get right. */
export const KITTIWAKE_WITHHELD: readonly string[] = ${JSON.stringify(withheld.sort(), null, 2).replace(/"/g, "'")};

/** Everything the router serves. */
export const KITTIWAKE_ROUTES: readonly string[] = ${JSON.stringify(all, null, 2).replace(/"/g, "'")};
`;

writeFileSync('src/lib/kittiwake-routes.generated.ts', file);
console.log(
  `${all.length} routes written (${described.length} described, ${withheld.length} withheld)`,
);
